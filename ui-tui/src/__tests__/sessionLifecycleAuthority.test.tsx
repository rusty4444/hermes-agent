it.each(['finish', 'invalidate'] as const)('reentrant successor keeps its lease through old %s cleanup', operation => {
  const authority = new SessionAdoption()
  const old = authority.begin()
  let current = old

  const stop = $sessionTransition.listen(value => {
    if (!value) {
      current = authority.begin()
    }
  })

  try {
    if (operation === 'finish') {
      authority.finish(old)
    } else {
      authority.invalidate()
    }

    expect(current).not.toBe(old)
    expect(authority.owns(current)).toBe(true)
    expect($sessionTransition.get()).toBe(current)
  } finally {
    stop()
    authority.dispose()
    $sessionTransition.set(null)
  }
})

function deferred<T>() {
  let resolve!: (value: T) => void
  let reject!: (error: Error) => void

  const promise = new Promise<T>((res, rej) => {
    resolve = res
    reject = rej
  })

  return { promise, resolve, reject }
}

const flush = async () => {
  await new Promise<void>(resolve => setImmediate(resolve))
  await new Promise<void>(resolve => setImmediate(resolve))
}

interface Frame {
  id: string
  method?: string
  params?: Record<string, unknown>
}

function mountAuthority() {
  const frames: Frame[] = []
  const requests: ServerRequest[] = []
  const gates = new Map<string, ReturnType<typeof deferred<void>>>()
  const locks: ReturnType<typeof deferred<unknown>>[] = []
  let lockCount = 0

  const gateway = Object.assign(new EventEmitter(), {
    request: vi.fn(async (method: string, params: Record<string, unknown> = {}): Promise<unknown> => {
      if (method === 'clarify.lock') {
        return locks[lockCount++]?.promise ?? { status: 'ok', remaining: [] }
      }

      if (
        ![
          'setup.status',
          'session.activate',
          'session.resume',
          'session.create',
          'session.close',
          'session.title'
        ].includes(method)
      ) {
        return null
      }

      const result = await channel.request(method, params)
      await gates.get(String(params.session_id ?? method))?.promise

      return result
    }),
    drain: vi.fn(),
    start: vi.fn(),
    kill: vi.fn(),
    notify: vi.fn(),
    getLogTail: () => []
  })

  const channel = new JsonRpcRequestChannel({ requestTimeoutMs: 0, onEvent: event => gateway.emit('event', event) })
  channel.attach({ send: text => frames.push(JSON.parse(text) as Frame) })
  channel.onRequest(request => {
    requests.push(request)
    gateway.emit('request', request)

    return true
  })
  let app!: ReturnType<typeof useMainApp>

  function Probe() {
    app = useMainApp(gateway as never)
    const a = app.appActions

    return (
      <Box>
        <PromptZone
          cols={100}
          onApprovalChoice={a.answerApproval}
          onClarifyCancel={a.cancelClarify}
          onClarifyQuestionAnswer={a.answerClarifyQuestion}
          onSecretSubmit={a.answerSecret}
          onSudoSubmit={a.answerSudo}
          onVaultCodeSubmit={a.answerVaultCode}
          onVaultSaveLoginSubmit={a.answerVaultSaveLogin}
          onVaultUnlockSubmit={a.answerVaultUnlock}
        />
      </Box>
    )
  }

  const stream = () => Object.assign(new PassThrough(), { columns: 100, rows: 30, isTTY: false })
  const stdout = stream()
  stdout.on('data', () => {})
  const stdin = Object.assign(new PassThrough(), { isTTY: true, setRawMode: () => {}, ref: () => {}, unref: () => {} })

  const view = renderSync(<Probe />, {
    stdin: stdin as never,
    stdout: stdout as never,
    stderr: stream() as never,
    patchConsole: false,
    exitOnCtrlC: false
  })

  const frame = (value: unknown) => channel.handleFrame(JSON.stringify(value))

  return {
    app: () => app,
    lifecycle: () => lifecycle,
    gateway,
    frames,
    stdin,
    frame,
    live: (method: string, id: string, sid: string, params: Record<string, unknown>) => {
      frame({ jsonrpc: '2.0', method, id, params: { session_id: sid, ...params } })

      return requests.at(-1)!
    },
    call: async (method: string, sid?: string) => {
      await vi.waitFor(() =>
        expect(frames.some(f => f.method === method && (!sid || f.params?.session_id === sid))).toBe(true)
      )

      return frames.findLast(f => f.method === method && (!sid || f.params?.session_id === sid))!
    },
    reply: (call: Frame, result: unknown) => frame({ jsonrpc: '2.0', id: call.id, result }),
    fail: (call: Frame, code = 5016) =>
      frame({ jsonrpc: '2.0', id: call.id, error: { code, message: 'SYNTHETIC_FAILURE' } }),
    hold: (key: string) => {
      const gate = deferred<void>()
      gates.set(key, gate)

      return gate
    },
    lock: () => {
      const lock = deferred<unknown>()
      locks.push(lock)

      return lock
    },
    close: () => {
      view.unmount()
      view.cleanup()

      for (const gate of gates.values()) {
        gate.resolve()
      }

      for (const lock of locks) {
        lock.resolve(null)
      }

      channel.detach(new Error('Fixture teardown'))
    }
  }
}

type Harness = ReturnType<typeof mountAuthority>

const questions = [
  { qid: 'q1', question: 'FIRST', choices: ['One'] },
  { qid: 'q2', question: 'SECOND', choices: ['Two'] }
]

const replay = (sid = 'runtime-A', id = 'question') => ({
  id,
  method: 'clarify',
  params: { session_id: sid, questions }
})

const payload = (sid: string, open_requests: unknown[] = []) => ({
  session_id: sid,
  session_key: `durable-${sid}`,
  running: false,
  status: 'idle',
  messages: [],
  open_requests
})

const history = (h: Harness) => JSON.stringify(h.app().appTranscript.historyItems)

async function begin(h: Harness, operation: 'activate' | 'resume', target = 'target') {
  if (operation === 'activate') {
    h.app().appActions.activateLiveSession(target)
  } else {
    h.app().appActions.resumeById(target)
    h.reply(await h.call('setup.status'), { provider_configured: true })
  }

  return h.call(`session.${operation}`, target)
}

async function admittedLock(h: Harness) {
  h.live('clarify', 'question', 'runtime-A', { questions })
  await vi.waitFor(() => expect(h.app().appActions.answerClarifyQuestion).toBeTypeOf('function'))
  await flush() // Commit the real card before this native gesture.
  const lock = h.lock()
  h.stdin.write('\x1b[13u')
  await vi.waitFor(() => expect(h.gateway.request.mock.calls.filter(([m]) => m === 'clarify.lock')).toHaveLength(1))

  return lock
}

const completion = (outcome: 'partial' | 'final' | 'expired') => ({
  status: outcome === 'expired' ? 'expired' : 'ok',
  remaining: outcome === 'partial' ? ['q2'] : []
})

function expectProgress(outcome: 'partial' | 'final' | 'expired') {
  if (outcome === 'partial') {
    expect(getOverlayState().clarify?.answers).toEqual({ q1: 'One' })
    expect(getServerRequest('question')).toBeDefined()
  } else {
    expect(getOverlayState().clarify).toBeNull()
    expect(getServerRequest('question')).toBeUndefined()
  }
}

for (const operation of ['activate', 'resume'] as const) {
  it.each(['partial', 'final', 'expired'] as const)(
    `${operation} failure retains admitted %s completion without reopening gesture admission`,
    async outcome => {
      const h = mountAuthority()

      try {
        const lock = await admittedLock(h)
        const call = await begin(h, operation)
        h.app().appActions.answerClarifyQuestion('q2', 'UNADMITTED')
        lock.resolve(completion(outcome))
        await flush()
        expectProgress(outcome)
        expect($isBlocked.get()).toBe(true)
        h.fail(call)
        await flush()
        expect(getUiState().sid).toBe('runtime-A')
        expectProgress(outcome)
        expect(h.gateway.request.mock.calls.filter(([m]) => m === 'clarify.lock')).toHaveLength(1)

        if (outcome === 'final') {
          expect(history(h)).toContain('FIRST → One')
        }
      } finally {
        h.close()
      }
    }
  )

  for (const order of ['before-replay', 'after-replay'] as const) {
    it.each(['partial', 'final', 'expired'] as const)(
      `${operation} same-session snapshot cannot roll back %s progress ${order}`,
      async outcome => {
        const h = mountAuthority()

        try {
          const lock = await admittedLock(h)
          const gate = h.hold('target')
          const call = await begin(h, operation)
          const snapshot = payload('runtime-A', [replay()])

          if (order === 'after-replay') {
            h.reply(call, snapshot)
          }

          lock.resolve(completion(outcome))
          await flush()

          if (order === 'before-replay') {
            h.reply(call, snapshot)
          }

          gate.resolve()
          await flush()
          expect($sessionTransition.get()).toBeNull()
          expectProgress(outcome)

          if (outcome === 'final') {
            expect(history(h)).toContain('FIRST → One')
          }

          if (outcome === 'partial') {
            await flush()
            h.stdin.write('\x1b[13u')
            await vi.waitFor(() =>
              expect(h.gateway.request).toHaveBeenCalledWith('clarify.lock', {
                request_id: 'question',
                question_id: 'q2',
                answer: 'Two'
              })
            )
          }
        } finally {
          h.close()
        }
      }
    )
  }
}

